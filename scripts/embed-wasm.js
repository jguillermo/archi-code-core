#!/usr/bin/env node
'use strict';

const fs = require('fs');
const path = require('path');
const zlib = require('zlib');
const { findNodeGlobal, SPECIFIER_RE } = require('./lib/web-safety');

const ROOT = process.cwd();
const [, , glueBase, output] = process.argv;

function fail(message) {
  console.error(`embed-wasm: FAIL — ${message}`);
  process.exit(1);
}

if (!glueBase || !output) {
  fail('usage: node embed-wasm.js <wasm-bindgen output without extension> <generated .ts file>');
}

const gluePath = path.join(ROOT, `${glueBase}.js`);
const wasmPath = path.join(ROOT, `${glueBase}_bg.wasm`);
for (const file of [gluePath, wasmPath]) {
  if (!fs.existsSync(file))
    fail(`${path.relative(ROOT, file)} does not exist — build the wasm first`);
}

const original = fs.readFileSync(gluePath, 'utf8');
if (!original.startsWith('let wasm_bindgen = (function(exports) {')) {
  fail('the glue is not wasm-bindgen --target no-modules output');
}
const glue = original.replace(/(?<![.\w$])exports\b/g, 'bindings');
const nodeGlobal = findNodeGlobal(glue);
if (nodeGlobal) fail(`the glue still uses the Node-only global "${nodeGlobal}"`);
const specifier = [...glue.matchAll(SPECIFIER_RE)][0];
if (specifier) fail(`the glue imports "${specifier[2]}"`);

const wasm = fs.readFileSync(wasmPath);
const base64 = zlib.gzipSync(wasm, { level: 9 }).toString('base64');
const banner = '// Generated by scripts/embed-wasm.js from the Rust crate. Do not edit.\n';
const source =
  banner +
  `export const WASM_GZIP_BASE64: string = '${base64}';\n` +
  `export const WASM_GLUE: string = ${JSON.stringify(glue)};\n`;

const sourceGlobal = findNodeGlobal(source);
if (sourceGlobal) fail(`the generated module would contain the Node-only global "${sourceGlobal}"`);

const target = path.join(ROOT, output);
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, source);
console.log(
  `embed-wasm: wrote ${output} (wasm ${(wasm.length / 1024).toFixed(0)} KiB, ${(base64.length / 1024).toFixed(0)} KiB as gzip + base64, glue ${(glue.length / 1024).toFixed(0)} KiB)`,
);
