import { describe, expect, it } from 'vitest';
import { parseDate, parseNumber } from '../src/parse-scalar';

describe('parseNumber', () => {
  it.each([
    [18, 18],
    [-1.5, -1.5],
    ['18', 18],
    ['-0.25', -0.25],
    ['007', 7],
  ])('accepts %o', (value, expected) => {
    expect(parseNumber(value)).toBe(expected);
  });

  it.each([
    [Number.NaN],
    [Number.POSITIVE_INFINITY],
    [''],
    [' 12 '],
    ['0x10'],
    ['1e3'],
    ['12.'],
    ['.5'],
    ['+1'],
    ['Infinity'],
    ['9'.repeat(400)],
    [true],
    [null],
  ])('rejects %o', (value) => {
    expect(parseNumber(value)).toBeNull();
  });
});

describe('parseDate', () => {
  it.each([
    ['2024-01-01', '2024-01-01T00:00:00.000Z'],
    ['2024-02-29', '2024-02-29T00:00:00.000Z'],
    ['2024-01-01T10:20Z', '2024-01-01T10:20:00.000Z'],
    ['2024-01-01T10:20:30Z', '2024-01-01T10:20:30.000Z'],
    ['2024-01-01T10:20:30.5Z', '2024-01-01T10:20:30.500Z'],
    ['2024-01-01T10:20:30.123Z', '2024-01-01T10:20:30.123Z'],
    ['2024-01-01T10:00:00+02:00', '2024-01-01T08:00:00.000Z'],
    ['2024-01-01T00:30:00-01:15', '2024-01-01T01:45:00.000Z'],
    ['0050-06-15', '0050-06-15T00:00:00.000Z'],
    [1_700_000_000_000, '2023-11-14T22:13:20.000Z'],
    [-86_400_000, '1969-12-31T00:00:00.000Z'],
    [0, '1970-01-01T00:00:00.000Z'],
    [new Date(Date.UTC(2024, 0, 1)), '2024-01-01T00:00:00.000Z'],
  ])('accepts %o', (value, expected) => {
    expect(parseDate(value)?.toISOString()).toBe(expected);
  });

  it.each([
    ['1'.repeat(0)],
    ['March 7'],
    ['2024-01-01T00:00'],
    ['2024-01-01T00:00:00'],
    ['2024-1-1'],
    ['2024-02-30'],
    ['2023-02-29'],
    ['2024-13-01'],
    ['2024-00-10'],
    ['2024-01-01T24:00Z'],
    ['2024-01-01T10:60Z'],
    ['2024-01-01T10:00:60Z'],
    ['2024-01-01T10:00+24:00'],
    ['2024-01-01T10:00+02:60'],
    ['2024-01-01 10:00Z'],
    ['1700000000000'],
    ['2024'],
    ['-86400000'],
    [1.5],
    [Number.NaN],
    [8.64e15 + 1],
    [new Date(Number.NaN)],
    [true],
    [null],
  ])('rejects %o', (value) => {
    expect(parseDate(value)).toBeNull();
  });
});
